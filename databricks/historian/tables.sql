-- Historian tables for the Zerobus Ignition connector.
-- Replace <catalog> and <schema>, then run the whole file. Every statement is idempotent.

USE CATALOG <catalog>;
USE SCHEMA <schema>;

-- ---------------------------------------------------------------------------
-- Landing tables written by the connector through Zerobus.
-- Columns must match module/src/main/proto/historian.proto. Zerobus cannot populate
-- identity or generated columns, so these tables stay plain.
-- ---------------------------------------------------------------------------

-- Append-only reading landing table; may contain retries/duplicates.
-- Change data feed exposes each row's landing commit time, which becomes metrics.ingest_time.
CREATE TABLE IF NOT EXISTS metrics_ingest (
  metric_id     STRING,
  time          TIMESTAMP,
  quality       BIGINT,
  value_int     BIGINT,
  value_double  DOUBLE,
  value_bool    BOOLEAN,
  value_text    STRING,
  value_ts      TIMESTAMP,
  value_bytes   BINARY,
  value_json    STRING
)
TBLPROPERTIES (delta.enableChangeDataFeed = true);

-- Append-only history of observed metadata snapshots, one row per producer/provider/path revision.
CREATE TABLE IF NOT EXISTS metric_metadata_events (
  metric_id             STRING,
  producer_id           STRING,
  tag_provider          STRING,
  tag_path              STRING,
  is_active             BOOLEAN,
  hierarchy             ARRAY<STRUCT<level_name: STRING, level_value: STRING>>,
  device_tag_name       STRING,
  source_ref            STRING,
  data_type             STRING,
  history_enabled       BOOLEAN,
  history_max_age_ms    BIGINT,
  quality_system        STRING,
  engineering_units     STRING,
  description           STRING,
  metadata_observed_at  TIMESTAMP,
  identity_mode         STRING,
  identity_key          STRING,
  metadata_revision     BIGINT
);

-- Collector startup/heartbeat/shutdown events. Zerobus rejects tables with column defaults, so there is no
-- Databricks-assigned ingest time here.
CREATE TABLE IF NOT EXISTS collector_events (
  producer_id  STRING,
  session_id   STRING,
  time         TIMESTAMP,
  event_type   STRING
);

-- ---------------------------------------------------------------------------
-- Tables maintained by the historian pipeline (historian_pipeline.py). They are ordinary
-- managed tables, not pipeline datasets, so a pipeline full refresh never truncates them.
-- ---------------------------------------------------------------------------

-- Permanent, deduplicated historical readings.
CREATE TABLE IF NOT EXISTS metrics (
  metric_id     STRING NOT NULL,
  time          TIMESTAMP NOT NULL,
  ingest_time   TIMESTAMP,
  quality       BIGINT NOT NULL,
  value_int     BIGINT,
  value_double  DOUBLE,
  value_bool    BOOLEAN,
  value_text    STRING,
  value_ts      TIMESTAMP,
  value_bytes   BINARY,
  value_json    STRING
)
CLUSTER BY (metric_id, time);

-- Permanent identity and numeric-ID mapping. metric_num is generated by Delta and can never be
-- supplied or updated; append-only blocks updates and deletes.
CREATE TABLE IF NOT EXISTS metric_registry (
  metric_id      STRING NOT NULL,
  metric_num     BIGINT GENERATED ALWAYS AS IDENTITY (START WITH 1 INCREMENT BY 1),
  identity_mode  STRING NOT NULL,
  identity_key   STRING NOT NULL
)
TBLPROPERTIES (delta.appendOnly = true);

-- Current state of each producer/provider/path binding (one row per binding, not per metric).
CREATE TABLE IF NOT EXISTS metric_catalog (
  metric_id             STRING,
  producer_id           STRING,
  tag_provider          STRING,
  tag_path              STRING,
  is_active             BOOLEAN,
  hierarchy             ARRAY<STRUCT<level_name: STRING, level_value: STRING>>,
  device_tag_name       STRING,
  source_ref            STRING,
  data_type             STRING,
  history_enabled       BOOLEAN,
  history_max_age_ms    BIGINT,
  quality_system        STRING,
  engineering_units     STRING,
  description           STRING,
  metadata_observed_at  TIMESTAMP
);
